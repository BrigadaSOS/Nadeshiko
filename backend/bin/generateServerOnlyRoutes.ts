/**
 * Generates the list of routes the frontend `/v1` proxy must refuse to forward
 * for a browser, from the `x-server-only` marker in the OpenAPI spec.
 *
 * Why the proxy has to be told at all: it stamps every request it forwards with
 * the shared internal secret, because that is how the backend's rate limiter
 * and traffic classifier recognise our own frontend. A backend route that
 * checks the same secret to mean "our own SERVER is asking" therefore cannot
 * tell a Nitro-side call from a browser call the proxy relayed -- and the
 * Shirabe credential route was reachable from any script on the site through
 * exactly that door. The marker in the spec is the single statement of which
 * routes are server-only; this turns it into the proxy's deny list, and the
 * agreement test pins it to the route auth the same spec produces.
 *
 * One output rather than two: the backend controllers keep their own
 * `isInternalProxyRequest` check (the inner door), and only the proxy needs a
 * list.
 */
import { mkdirSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { pathToFileURL } from 'url';
import { listOperations, loadBundledSpec, type SpecOperation } from './lib/spec';

const FRONTEND_OUTPUT_FILE = resolve(import.meta.dirname, '../../frontend/server/utils/generated/serverOnlyRoutes.ts');

/** Exported so the agreement test reads the same predicate the generator does. */
export function isServerOnly(op: Pick<SpecOperation, 'isServerOnly'>): boolean {
  return op.isServerOnly;
}

function render(routes: { method: string; path: string }[]): string {
  const lines: string[] = [
    '/** AUTOGENERATED from OpenAPI `x-server-only` markers — DO NOT EDIT **/',
    '/** Regenerate with `npm run generate:api` in ../backend. **/',
    '',
    '/**',
    ' * Routes the Nitro `/v1` proxy refuses to forward for a browser, however it is',
    ' * authenticated. They exist for calls this server makes on its own behalf',
    ' * (server/utils/shirabeReader.ts), and the backend gates them on the internal',
    ' * secret the proxy would otherwise stamp onto a relayed browser request. Paths',
    ' * keep their OpenAPI `{param}` templates.',
    ' */',
    'export interface ServerOnlyRoute {',
    '  method: string;',
    '  path: string;',
    '}',
    '',
    'export const serverOnlyRoutes: ServerOnlyRoute[] = [',
  ];

  for (const route of routes) {
    lines.push(`  { method: '${route.method}', path: '${route.path}' },`);
  }

  lines.push('];');
  lines.push('');

  return lines.join('\n');
}

function generate(): void {
  const spec = loadBundledSpec();
  const routes = listOperations(spec)
    .filter(isServerOnly)
    .map((op) => ({ method: op.method.toUpperCase(), path: op.path }));

  mkdirSync(dirname(FRONTEND_OUTPUT_FILE), { recursive: true });
  writeFileSync(FRONTEND_OUTPUT_FILE, render(routes));
  console.log(`Generated ${FRONTEND_OUTPUT_FILE} with ${routes.length} server-only route entries.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  generate();
}
