/** Generates the shared public-route allowlist from OpenAPI security. The proxy may inject the admin master key only
 * for API-key-only routes over shared corpus data; backend CORS and Nitro must consume the same list, while
 * separate package builds require separate outputs. */
import { mkdirSync, writeFileSync } from 'fs';
import { resolve, dirname, join } from 'path';
import { pathToFileURL } from 'url';
import { ApiPermission } from '@app/models/ApiPermission';
import { listOperations, loadBundledSpec, type SecurityRequirement } from './lib/spec';
import { resolveGeneratedDir } from './lib/generatedReady';

const FRONTEND_OUTPUT_FILE = resolve(import.meta.dirname, '../../frontend/server/utils/generated/publicApiRoutes.ts');
const BACKEND_OUTPUT_FILE = join(resolveGeneratedDir(), 'publicApiRoutes.ts');

/** Only scopes reading shared corpus data qualify; owner/profile, activity, collection, and write scopes must never
 * use the admin master key for a browser. */
const CORPUS_READ_PERMISSIONS = new Set<string>([ApiPermission.READ_MEDIA]);

/** Whether an anonymous browser may use the proxy for this operation; exported so the cross-generator test can
 * compare it with auth middleware. */
export function isProxyPublic(security: SecurityRequirement[] | undefined): boolean {
  if (!security || security.length === 0) return false;
  if (security.some((requirement) => 'SessionCookie' in requirement)) return false;

  const apiKeyRequirements = security.filter((requirement) => 'ApiKey' in requirement);
  if (apiKeyRequirements.length !== security.length) return false;

  return apiKeyRequirements.every((requirement) => {
    const permissions = requirement.ApiKey;
    // Fail closed: a requirement with no permission list is not provably read-only.
    if (!permissions) return false;
    return permissions.every((permission) => CORPUS_READ_PERMISSIONS.has(permission));
  });
}

type PublicRoute = { method: string; path: string };

function render(routes: PublicRoute[], docComment: string, regenerateHint: string): string {
  const lines: string[] = [
    '/** AUTOGENERATED from OpenAPI security definitions — DO NOT EDIT **/',
    `/** Regenerate with \`npm run generate:api\` ${regenerateHint}. **/`,
    '',
    docComment,
    'export interface PublicApiRoute {',
    '  method: string;',
    '  path: string;',
    '}',
    '',
    'export const publicApiRoutes: PublicApiRoute[] = [',
  ];

  for (const route of routes) {
    lines.push(`  { method: '${route.method}', path: '${route.path}' },`);
  }

  lines.push('];');
  lines.push('');

  return lines.join('\n');
}

function write(file: string, contents: string, routeCount: number): void {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, contents);
  console.log(`Generated ${file} with ${routeCount} public route entries.`);
}

function generate(): void {
  const spec = loadBundledSpec();
  const routes: PublicRoute[] = [];

  for (const op of listOperations(spec)) {
    if (!isProxyPublic(op.security)) continue;

    routes.push({ method: op.method.toUpperCase(), path: op.path });
  }

  write(
    FRONTEND_OUTPUT_FILE,
    render(
      routes,
      [
        '/**',
        ' * Routes the Nitro proxy may call with the shared master API key on behalf of',
        ' * an unauthenticated browser. Paths keep their OpenAPI `{param}` templates.',
        ' */',
      ].join('\n'),
      'in ../backend',
    ),
    routes.length,
  );

  write(
    BACKEND_OUTPUT_FILE,
    render(
      routes,
      [
        '/**',
        ' * Routes a browser on any origin may call cross-origin, which is the same set',
        ' * the Nitro proxy may call with the master key: both mean "this response is the',
        ' * shared corpus, not somebody\'s account data". Paths keep their OpenAPI',
        ' * `{param}` templates -- see `@lib/publicRoutes` for the matcher.',
        ' */',
      ].join('\n'),
      'in this package',
    ),
    routes.length,
  );
}

// Generate only as a script; agreement-test imports must not rewrite the frontend allowlist.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  generate();
}
