/**
 * Generates the frontend proxy's public-route allowlist from OpenAPI security
 * definitions.
 *
 * The Nitro proxy stamps browser requests that carry no credentials with the
 * shared master API key. That key belongs to the admin service account, so
 * injecting it on an owner-scoped route would hand the caller the service
 * account's own data. A route may therefore only be injected into when it is
 * reachable with an API key alone and every scope it needs reads the shared
 * media corpus rather than one account's data.
 *
 * Output lands in the frontend tree (committed, like backend/generated) so the
 * Nitro build never has to reach across package boundaries.
 */
import { readFileSync, mkdirSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { parse } from 'yaml';
import { ApiPermission } from '@app/models/ApiPermission';

const BUNDLED_SPEC = resolve(import.meta.dir, '../docs/generated/openapi.yaml');
const OUTPUT_FILE = resolve(import.meta.dir, '../../frontend/server/utils/generated/publicApiRoutes.ts');

/**
 * Scopes that read the shared corpus and nothing account-specific. Everything
 * else — profile, activity, collections, and every write scope — resolves data
 * from the key owner, so the master key must never stand in for the browser.
 */
const CORPUS_READ_PERMISSIONS = new Set<string>([ApiPermission.READ_MEDIA]);

const METHODS = ['get', 'post', 'patch', 'put', 'delete'] as const;

interface SecurityRequirement {
  [scheme: string]: string[];
}

interface Operation {
  security?: SecurityRequirement[];
}

type PathItem = Partial<Record<(typeof METHODS)[number], Operation>>;

function isProxyPublic(security: SecurityRequirement[] | undefined): boolean {
  if (!security || security.length === 0) return false;
  if (security.some((requirement) => 'SessionCookie' in requirement)) return false;

  const apiKeyRequirements = security.filter((requirement) => 'ApiKey' in requirement);
  if (apiKeyRequirements.length !== security.length) return false;

  return apiKeyRequirements.every((requirement) => {
    const permissions = requirement.ApiKey;
    // Fail closed: a requirement with no permission list is not provably read-only.
    if (!permissions) return false;
    return permissions.every((permission) => CORPUS_READ_PERMISSIONS.has(permission));
  });
}

function generate(): void {
  const spec = parse(readFileSync(BUNDLED_SPEC, 'utf8'));
  const paths: Record<string, PathItem> = spec.paths;
  const routes: { method: string; path: string }[] = [];

  for (const [path, pathItem] of Object.entries(paths)) {
    for (const method of METHODS) {
      const operation = pathItem[method];
      if (!operation) continue;
      if (!isProxyPublic(operation.security)) continue;

      routes.push({ method: method.toUpperCase(), path });
    }
  }

  const lines: string[] = [
    '/** AUTOGENERATED from OpenAPI security definitions — DO NOT EDIT **/',
    '/** Regenerate with `bun run generate:api` in ../backend. **/',
    '',
    '/**',
    ' * Routes the Nitro proxy may call with the shared master API key on behalf of',
    ' * an unauthenticated browser. Paths keep their OpenAPI `{param}` templates.',
    ' */',
    'export interface PublicApiRoute {',
    '  method: string;',
    '  path: string;',
    '}',
    '',
    'export const publicApiRoutes: PublicApiRoute[] = [',
  ];

  for (const route of routes) {
    lines.push(`  { method: '${route.method}', path: '${route.path}' },`);
  }

  lines.push('];');
  lines.push('');

  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(OUTPUT_FILE, lines.join('\n'));
  console.log(`Generated ${OUTPUT_FILE} with ${routes.length} public route entries.`);
}

generate();
