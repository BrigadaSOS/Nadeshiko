import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

const SCRIPT = fileURLToPath(new URL('../../bin/generateOutputTypes.ts', import.meta.url));

/**
 * A minimal stand-in for @nahkies/openapi-code-generator output: one named
 * schema parsed as a request body, typed in the body slot of a
 * `Params<P, Q, B, H>` generic. That generic's shape is the only thing the
 * post-processor keys off, so it is the thing worth pinning.
 */
const SCHEMAS = `import { z } from 'zod/v4';

export const s_Thing = z.object({ limit: z.coerce.number().optional().default(10) });
`;

const route = (params: string) => `/** AUTOGENERATED - DO NOT EDIT **/
import { type Params } from '@nahkies/typescript-express-runtime/server';
import { parseRequestInput } from '@nahkies/typescript-express-runtime/zod-v4';
import type { t_Thing } from '../models.ts';
import { s_Thing } from '../schemas.ts';

export type CreateThing = (
  params: ${params},
) => Promise<void>;

const createThing = {
  body: parseRequestInput(s_Thing, request.body),
};
`;

let generatedDir: string;

/** Runs the script the way `generate:api` does, and reports how it exited. */
function runScript(): { status: number; output: string } {
  try {
    const stdout = execFileSync('node', ['--import', 'tsx', SCRIPT], {
      env: { ...process.env, GENERATED_DIR: generatedDir },
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return { status: 0, output: stdout };
  } catch (error) {
    const failure = error as { status?: number; stdout?: string; stderr?: string };
    return { status: failure.status ?? 1, output: `${failure.stdout ?? ''}${failure.stderr ?? ''}` };
  }
}

function writeRoute(params: string): void {
  fs.writeFileSync(path.join(generatedDir, 'routes', 'thing.ts'), route(params));
}

function readRoute(): string {
  return fs.readFileSync(path.join(generatedDir, 'routes', 'thing.ts'), 'utf-8');
}

beforeEach(() => {
  generatedDir = fs.mkdtempSync(path.join(os.tmpdir(), 'output-types-'));
  fs.mkdirSync(path.join(generatedDir, 'routes'));
  fs.writeFileSync(path.join(generatedDir, 'schemas.ts'), SCHEMAS);
});

afterEach(() => {
  fs.rmSync(generatedDir, { recursive: true, force: true });
});

describe('generateOutputTypes', () => {
  it('rewrites the body slot to the output type and imports it', () => {
    writeRoute('Params<void, void, t_Thing, void>');

    expect(runScript().status).toBe(0);

    const content = readRoute();
    expect(content).toContain('Params<void, void, ThingOutput, void>');
    expect(content).toContain("import type { ThingOutput } from '../outputTypes.ts';");
    expect(fs.existsSync(path.join(generatedDir, 'outputTypes.ts'))).toBe(true);
  });

  // The rewrites are anchored on a type's position inside the generic, so an
  // upgrade that reshapes it makes them match nothing. Failing open here would
  // leave the backend compiling against Zod input types -- defaults missing
  // from the types, and everything still typechecking.
  it('fails when the body type moves to a slot the pattern does not reach', () => {
    writeRoute('Params<void, void, void, t_Thing>');

    const { status, output } = runScript();

    expect(status).not.toBe(0);
    expect(output).toContain('t_Thing');
    expect(readRoute()).toContain('t_Thing');
  });

  it('fails when the generic is renamed rather than reshaped', () => {
    writeRoute('RouteArgs<void, void, t_Thing, void>');

    const { status, output } = runScript();

    expect(status).not.toBe(0);
    expect(output).toContain('no Params<> generic was rewritten');
  });
});
